/// Pitch destinations: ±100 % = ±48 st.
const fn st(semis: f32) -> f32 {
    semis / 48.0 * 100.0
}
/// Cutoff destination: ±100 % = ±8 octaves.
const fn oct(o: f32) -> f32 {
    o / 8.0 * 100.0
}

/// A matrix slot: source, destination, amount %.
type Slot = (f32, f32, f32);

fn pr(name: &'static str, category: &'static str, kv: &[(usize, f32)], slots: &[Slot]) -> Preset {
    let mut patch = defaults();
    for &(i, v) in kv {
        patch[i] = v;
    }
    assert!(slots.len() <= super::params::SLOTS, "{name}: too many matrix slots");
    for (s, &(src, dst, amt)) in slots.iter().enumerate() {
        patch[ix::M1_SRC + 3 * s] = src;
        patch[ix::M1_DST + 3 * s] = dst;
        patch[ix::M1_AMT + 3 * s] = amt;
    }
    Preset { name, category, patch }
}

